"""scripts/llm/scope.py — deterministic NCERT-1-5 syllabus scope gate.

Live-reported gap: the out-of-grade boundary previously had NO code-level
check at all -- it was 100% the model's own judgment, steered only by prose
in prompt_registry.TUTOR_SYSTEM ("ONLY refuse if the topic is clearly beyond
primary school (algebra, square roots, trigonometry, calculus,
integration...)"), with five example names as illustrative guidance, not an
enumerated boundary. Confirmed live this is unreliable in BOTH directions:
  - "what is algebra" / "what is integration" got a full worked example with
    a formula and a practice invitation, violating the prompt's own "no
    formulas, no procedure, no worked example" rule for a bare "what is X".
  - "solve this integral: integral of x dx" -- an EXPLICIT request to solve
    something beyond primary school -- was not refused at all; it got a
    full worked-example walkthrough, the one case the system prompt is
    most explicit should hard-refuse.

This module is the deterministic backstop, mirroring safety.py's own
pattern (a bounded, keyword/pattern-based check, run BEFORE any LLM call
sees the text, not an LLM classifier) rather than hoping the prompt holds
better:
  - A topic from BEYOND_PRIMARY_TOPICS, named with anything beyond a bare
    "what is X" (a solve/calculate/perform request, or a concrete problem
    instance) -> hard refusal, generated by NEITHER this module NOR the
    main tutor prompt -- the fixed, existing refusal sentinel, with ZERO
    LLM call, so there is no chance of the model working through it anyway.
  - A bare "what is X" / "what does X mean" for that same topic -> still
    needs a genuine LLM-generated gloss, but routed through a small,
    single-purpose prompt (see generate_gloss) instead of hoping the large,
    multi-purpose TUTOR_SYSTEM prompt's prose rule holds -- the same
    "narrow prompt is more reliable than a rule buried in a big one"
    lesson already applied to intent classification and conversation
    resolution elsewhere in this package.
  - Anything that names a beyond-primary topic WITHOUT clearly being a bare
    definition ask (e.g. mixes in extra content, a formula, "and can you
    also...") defaults to REFUSE, not GLOSS -- the failure mode being
    guarded against (an unverified worked explanation of something outside
    the syllabus) is worse than an occasional over-cautious refusal here.

BEYOND_PRIMARY_TOPICS is grounded in, and should be kept in sync with,
docs/verified_ncert_class_1_5_topics.md -- every entry below names a branch
of mathematics that does not appear anywhere in that document's Class 1-5
breakdown. Entries are deliberately whole-concept names (regexes with word
boundaries), not single letters or operators, to keep false positives on
ordinary in-syllabus questions (which DO cover squares-the-shape, angles,
bar graphs, rounding/estimation, etc.) structurally unlikely.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

BEYOND_PRIMARY_TOPICS: tuple[tuple[str, str], ...] = (
    # Order matters: _find_topic returns the FIRST match, so a more
    # specific multi-word topic is listed before a shorter one it
    # contains ("matrix algebra" before bare "algebra"), same convention
    # scripts/llm/topics.py itself documents and follows.
    (r"\bmatri(?:x|ces)\b(?:\s+algebra)?", "matrix algebra"),
    (r"\balgebra\b|\balgebraic\b|"
     # An algebraic expression can show up with no literal "algebra" in
     # sight -- "^" used for exponentiation ("(x+1)^2"), or a letter in a
     # linear-equation shape ("2x+3=7"). NCERT 1-5 never uses either (see
     # docs/verified_ncert_class_1_5_topics.md) -- a caret in particular
     # has no legitimate Class 1-5 use at all.
     r"\^\s*\d|\b\d*[a-z]\s*[+\-]\s*\d+\s*=\s*\d+\b",
     "algebra"),
    (r"\bintegrat(?:ion|e|ing)\b|\bintegral\b", "integration"),
    (r"\bdifferentiat(?:ion|e|ing)\b|\bderivative\b", "differentiation"),
    (r"\bcalculus\b", "calculus"),
    (r"\btrigonometr\w*\b|\bsine\b|\bcosine\b|\btangent\b(?!.*(line|circle|touch))",
     "trigonometry"),
    (r"\bquadratic\b", "quadratic equations"),
    (r"\bsquare\s*roots?\b|\bcube\s*roots?\b", "roots (square/cube root)"),
    (r"\bpercentages?\b|\bpercent\b|%", "percentages"),
    (r"\bprobabilit\w*\b", "probability"),
    # "mean"/"mode"/"average" deliberately excluded as BARE triggers: all
    # three collide too easily with ordinary phrasing a Class 1-5 child
    # genuinely uses ("what do you mean by subtraction", "mode of
    # transport", "on average"). Only "median" and the word "statistics"
    # itself are unambiguous enough to flag on their own.
    (r"\bmedian\b|\bstatistics\b", "statistics"),
    (r"\blogarithms?\b|\blog\s*base\b", "logarithms"),
    (r"\bexponent(?:s|ial)?\b|\bpowers?\s+of\s+\d", "exponents"),
    (r"\bcomplex\s+numbers?\b", "complex numbers"),
    (r"\bpolynomials?\b", "polynomials"),
    (r"\bcoordinate\s+geometry\b|\bcartesian\b|\bx[\s-]axis\b|\by[\s-]axis\b|"
     r"\bgraph\s+of\s+(a|the)\s+function\b", "coordinate geometry"),
    (r"\bset\s+theory\b|\bvenn\s+diagram\b", "set theory"),
    (r"\bbinomial\b", "binomial expressions"),
    (r"\bvectors?\b", "vectors"),
    (r"\bpermutations?\b|\bcombinations?\b(?=.{0,20}\bchoose\b)", "permutations/combinations"),
)
_COMPILED_TOPICS = [(re.compile(p, re.IGNORECASE), label) for p, label in BEYOND_PRIMARY_TOPICS]

# Non-maths subjects -- a DIFFERENT, stricter case than the beyond-primary
# MATH topics above: the system prompt's own existing policy for these is
# refuse OUTRIGHT, never even a simple gloss (nothing here advances toward
# any in-syllabus maths goal the way "what is algebra" still does, one
# grade early). This is necessarily a REPRESENTATIVE, not exhaustive, list
# of common subjects a curious Class 1-5 child might ask a maths-tutor
# chatbot about -- unlike BEYOND_PRIMARY_TOPICS (grounded precisely against
# "every branch of maths not in docs/verified_ncert_class_1_5_topics.md"),
# "every non-maths topic in existence" has no such bounded ground truth.
# Patterns are deliberately SPECIFIC subject-identifying terms, never a
# generic noun that could appear in an ordinary word problem -- "plant" is
# excluded ("if a plant grows 2cm a day..." is a real multiplication
# problem); "photosynthesis" is not.
NON_MATH_SUBJECTS: tuple[tuple[str, str], ...] = (
    (r"\bphotosynthesis\b|\bbiology\b|\becosystems?\b|\bhabitats?\b|"
     r"\b(?:carni|herbi|omni)vores?\b|\bfood\s+chain\b|\bphotosynthesi[sz]e\b",
     "biology"),
    (r"\bchemistry\b|\bchemical\s+reactions?\b|\bmolecules?\b|\batoms?\b|"
     r"\bperiodic\s+table\b", "chemistry"),
    (r"\bphysics\b|\bgravity\b|\bvelocity\b|\bfriction\b|\belectricity\b|"
     r"\belectric\s+circuits?\b|\bmagnetis(?:m|e)\b", "physics"),
    (r"\bsolar\s+system\b|\bplanets?\b|\bgalax(?:y|ies)\b|\bastronom\w*\b|"
     r"\buniverse\b|\bconstellations?\b", "astronomy"),
    (r"\bhistory\b|\bfreedom\s+fighters?\b|\bindependence\s+day\b|"
     r"\bancient\s+(?:egypt|rome|india)\b|\bworld\s+war\b", "history"),
    (r"\bgeography\b|\bcontinents?\b|\bcapital\s+(?:city|of)\b|"
     r"\bcountr(?:y|ies)\s+(?:in|of)\b", "geography"),
    (r"\bgrammar\b|\bnouns?\b|\bverbs?\b|\badjectives?\b|\bpoems?\b|"
     r"\bessay\b|\bparagraph\s+writing\b|\bspelling\s+of\b", "language arts"),
    (r"\bcomputer\s+programming\b|\bcoding\b|\bpython\b|\bjavascript\b|"
     r"\bwebsite\b|\bapp\s+development\b", "computer science"),
    (r"\bcricket\s+(?:score|rules|match)\b|\bfootball\s+(?:rules|match)\b|"
     r"\bmovies?\b|\bcartoons?\b|\bvideo\s+games?\b", "general/entertainment"),
)
_COMPILED_NON_MATH = [(re.compile(p, re.IGNORECASE), label) for p, label in NON_MATH_SUBJECTS]

# "solve/calculate/perform the actual procedure" signals -- paired with a
# beyond-primary topic match, these force REFUSE regardless of phrasing.
_SOLVE_SIGNAL_RE = re.compile(
    r"\bsolve\b|\bcalculate\b|\bcompute\b|\bevaluate\b|\bwork\s*out\b|"
    r"\bfind\s+the\s+value\b|\bdifferentiate\b|\bintegrate\b|\bfactori[sz]e\b|"
    r"\bexpand\b|\bprove\b|\bderive\b|\bsimplify\b|"
    r"\bdx\b|\bd/dx\b",
    re.IGNORECASE,
)

# A bare "what is X" / "what does X mean" / "define X" ask, and NOTHING
# ELSE -- the one shape the system prompt says may still get a short
# gloss. Matched by stripping the recognised opening phrase and requiring
# the remainder to be a SHORT noun phrase (<=5 words), not by a raw
# character cap: "what is integration used for in physics problems like
# velocity" starts with "what is" too, but goes well beyond a bare
# definition ask, and a character cap alone doesn't catch that reliably.
_OPENING_RE = re.compile(
    r"^\s*(?:what\s+(?:is|are|does)|what'?s|define|tell\s+me\s+about|explain)\s+",
    re.IGNORECASE,
)
_LEADING_ARTICLE_RE = re.compile(r"^(?:a|an|the)\s+", re.IGNORECASE)
_TRAILING_MEAN_RE = re.compile(r"\s+means?$", re.IGNORECASE)
_BARE_DEFINITION_MAX_WORDS = 5


def _is_bare_definition(text: str) -> bool:
    t = (text or "").strip()
    m = _OPENING_RE.match(t)
    if not m:
        return False
    remainder = t[m.end():].strip().rstrip("?!.").strip()
    remainder = _LEADING_ARTICLE_RE.sub("", remainder)
    remainder = _TRAILING_MEAN_RE.sub("", remainder).strip()
    words = remainder.split()
    return 0 < len(words) <= _BARE_DEFINITION_MAX_WORDS

REFUSAL_TEXT = "Let's ask your teacher about this one!"


@dataclass
class ScopeResult:
    in_scope: bool
    topic: str | None = None       # the matched beyond-primary topic, if any
    allow_gloss: bool = False      # True iff a short "what is X" gloss is OK
    fallback_text: str | None = None  # set iff in_scope is False and not allow_gloss


def _find_topic(text: str) -> str | None:
    t = text or ""
    for pattern, label in _COMPILED_TOPICS:
        if pattern.search(t):
            return label
    return None


def _find_non_math_subject(text: str) -> str | None:
    t = text or ""
    for pattern, label in _COMPILED_NON_MATH:
        if pattern.search(t):
            return label
    return None


def check(text: str) -> ScopeResult:
    """Run BEFORE conversation_resolver/intent classification, same slot as
    safety.check_input. in_scope=False and allow_gloss=False means: stop
    here, return fallback_text, no resolver/retrieval/verifier/generation
    call for this turn at all.

    Non-maths subjects are checked FIRST and always refuse outright (no
    gloss, no bare-definition exception) -- that's the system prompt's own
    existing policy for them, just enforced deterministically instead of
    hoping the prose rule holds. A beyond-primary MATH topic gets the
    softer bare-definition-gloss treatment below."""
    non_math = _find_non_math_subject(text)
    if non_math is not None:
        return ScopeResult(in_scope=False, topic=non_math, allow_gloss=False,
                           fallback_text=REFUSAL_TEXT)

    topic = _find_topic(text)
    if topic is None:
        return ScopeResult(in_scope=True)

    t = (text or "").strip()
    if _SOLVE_SIGNAL_RE.search(t):
        return ScopeResult(in_scope=False, topic=topic, allow_gloss=False,
                           fallback_text=REFUSAL_TEXT)
    if _is_bare_definition(t):
        return ScopeResult(in_scope=False, topic=topic, allow_gloss=True)
    # Names a beyond-primary topic without being a clean bare-definition ask
    # (extra content mixed in) -- conservative default is REFUSE, not GLOSS.
    return ScopeResult(in_scope=False, topic=topic, allow_gloss=False,
                       fallback_text=REFUSAL_TEXT)


_GLOSS_SYSTEM = (
    "A Class 1-5 child (NCERT, India) asked what a maths topic is that is "
    "taught LATER, beyond primary school. Reply in 1-2 short, warm "
    "sentences with an honest, very simple idea of what it roughly means -- "
    "NO formulas, NO numbered steps, NO worked example, NO equations, and "
    "do NOT invite them to try a problem on it. End with one short "
    "sentence saying they will learn exactly how to do it later. Nothing "
    "else."
)
_GLOSS_FEWSHOT = [
    ("algebra", "Algebra is a way of doing maths where letters stand in for "
                "numbers we don't know yet. You'll learn exactly how to use "
                "it a little later on!"),
    ("integration", "Integration is a way mathematicians add up lots and "
                    "lots of tiny pieces to find a total, like area under a "
                    "curve. You'll learn exactly how it works in a later class!"),
    ("probability", "Probability is about how likely something is to "
                    "happen, like whether it will rain tomorrow. You'll "
                    "learn exactly how to work that out later on!"),
]


def generate_gloss(topic: str, chat_fn=None) -> str:
    """A small, single-purpose LLM call for the ONE case that still needs
    real generation (a bare "what is X" for a beyond-primary topic) --
    narrower and far more reliable than hoping the main TUTOR_SYSTEM
    prompt's prose rule holds inside a much longer, multi-purpose prompt
    (confirmed live it doesn't, reliably). chat_fn is injectable for tests."""
    from . import llm_client  # lazy: keeps this module import-safe offline

    messages = [{"role": "system", "content": _GLOSS_SYSTEM}]
    for q, a in _GLOSS_FEWSHOT:
        messages.append({"role": "user", "content": f"what is {q}"})
        messages.append({"role": "assistant", "content": a})
    messages.append({"role": "user", "content": f"what is {topic}"})

    # max_tokens=400, not a tight budget: confirmed live this reasoning
    # model can burn 150+ tokens on hidden thinking before emitting any
    # visible text at all (finish_reason="length", text=""), the same
    # failure mode already hardened against in verifier.py's extractor and
    # hints.py (see their own comments). A short gloss still only costs a
    # few hundred tokens even with headroom to spare.
    fn = chat_fn or (lambda msgs: llm_client.chat(
        msgs, params={"temperature": 0.3, "max_tokens": 400}))
    result = fn(messages)
    text = (result.get("text") or "").strip() if isinstance(result, dict) else (result or "").strip()
    if not text:
        text = (f"{topic.capitalize()} is something you'll learn more about "
                "in a later class!")
    return text
