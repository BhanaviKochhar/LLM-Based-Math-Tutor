"""scripts/llm/scope.py — deterministic NCERT-1-5 syllabus scope gate.

Live-reported gap: the out-of-grade boundary previously had NO code-level
check at all -- it was 100% the model's own judgment, steered only by prose
in prompt_registry.TUTOR_SYSTEM ("ONLY refuse if the topic is clearly beyond
primary school (algebra, square roots, trigonometry, calculus,
integration...)"), with five example names as illustrative guidance, not an
enumerated boundary. Confirmed live this is unreliable in BOTH directions:
  - "what is algebra" / "what is integration" got a full worked example with
    a formula and a practice invitation, violating the prompt's own "no
    formulas, no procedure, no worked example" rule for a bare "what is X".
  - "solve this integral: integral of x dx" -- an EXPLICIT request to solve
    something beyond primary school -- was not refused at all; it got a
    full worked-example walkthrough, the one case the system prompt is
    most explicit should hard-refuse.

This module is the deterministic backstop, mirroring safety.py's own
pattern (a bounded, keyword/pattern-based check, run BEFORE any LLM call
sees the text, not an LLM classifier) rather than hoping the prompt holds
better:
  - A topic from BEYOND_PRIMARY_TOPICS, named with anything beyond a bare
    "what is X" (a solve/calculate/perform request, or a concrete problem
    instance) -> hard refusal, generated by NEITHER this module NOR the
    main tutor prompt -- the fixed, existing refusal sentinel, with ZERO
    LLM call, so there is no chance of the model working through it anyway.
  - A bare "what is X" / "what does X mean" for that same topic -> still
    needs a genuine LLM-generated gloss, but routed through a small,
    single-purpose prompt (see generate_gloss) instead of hoping the large,
    multi-purpose TUTOR_SYSTEM prompt's prose rule holds -- the same
    "narrow prompt is more reliable than a rule buried in a big one"
    lesson already applied to intent classification and conversation
    resolution elsewhere in this package.
  - Anything that names a beyond-primary topic WITHOUT clearly being a bare
    definition ask (e.g. mixes in extra content, a formula, "and can you
    also...") defaults to REFUSE, not GLOSS -- the failure mode being
    guarded against (an unverified worked explanation of something outside
    the syllabus) is worse than an occasional over-cautious refusal here.

BEYOND_PRIMARY_TOPICS is grounded in, and should be kept in sync with,
docs/verified_ncert_class_1_5_topics.md -- every entry below names a branch
of mathematics that does not appear anywhere in that document's Class 1-5
breakdown. Entries are deliberately whole-concept names (regexes with word
boundaries), not single letters or operators, to keep false positives on
ordinary in-syllabus questions (which DO cover squares-the-shape, angles,
bar graphs, rounding/estimation, etc.) structurally unlikely.
"""
