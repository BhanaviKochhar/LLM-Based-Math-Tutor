# "solve/calculate/perform the actual procedure" signals -- paired with a
# beyond-primary topic match, these force REFUSE regardless of phrasing.
_SOLVE_SIGNAL_RE = re.compile(
    r"\bsolve\b|\bcalculate\b|\bcompute\b|\bevaluate\b|\bwork\s*out\b|"
    r"\bfind\s+the\s+value\b|\bdifferentiate\b|\bintegrate\b|\bfactori[sz]e\b|"
    r"\bexpand\b|\bprove\b|\bderive\b|\bsimplify\b|"
    r"\bdx\b|\bd/dx\b",
    re.IGNORECASE,
)

# A bare "what is X" / "what does X mean" / "define X" ask, and NOTHING
# ELSE -- the one shape the system prompt says may still get a short
# gloss. Matched by stripping the recognised opening phrase and requiring
# the remainder to be a SHORT noun phrase (<=5 words), not by a raw
# character cap: "what is integration used for in physics problems like
# velocity" starts with "what is" too, but goes well beyond a bare
# definition ask, and a character cap alone doesn't catch that reliably.
_OPENING_RE = re.compile(
    r"^\s*(?:what\s+(?:is|are|does)|what'?s|define|tell\s+me\s+about|explain)\s+",
    re.IGNORECASE,
)
_LEADING_ARTICLE_RE = re.compile(r"^(?:a|an|the)\s+", re.IGNORECASE)
_TRAILING_MEAN_RE = re.compile(r"\s+means?$", re.IGNORECASE)
_BARE_DEFINITION_MAX_WORDS = 5


def _is_bare_definition(text: str) -> bool:
    t = (text or "").strip()
    m = _OPENING_RE.match(t)
    if not m:
        return False
    remainder = t[m.end():].strip().rstrip("?!.").strip()
    remainder = _LEADING_ARTICLE_RE.sub("", remainder)
    remainder = _TRAILING_MEAN_RE.sub("", remainder).strip()
    words = remainder.split()
    return 0 < len(words) <= _BARE_DEFINITION_MAX_WORDS

REFUSAL_TEXT = "Let's ask your teacher about this one!"


@dataclass
class ScopeResult:
    in_scope: bool
    topic: str | None = None       # the matched beyond-primary topic, if any
    allow_gloss: bool = False      # True iff a short "what is X" gloss is OK
    fallback_text: str | None = None  # set iff in_scope is False and not allow_gloss
    matched_term: str | None = None   # the child's own words that matched ("median")


def _find_topic(text: str) -> tuple[str, str] | None:
    """(topic label, the matched words) for the first beyond-primary topic
    named, else the first beyond-primary concept described in plain words."""
    t = text or ""
    for compiled in (_COMPILED_TOPICS, _COMPILED_CONCEPTS):
        for pattern, label in compiled:
            m = pattern.search(t)
            if m:
                return label, m.group(0).strip()
    return None


def _find_non_math_subject(text: str) -> str | None:
    t = text or ""
    for pattern, label in _COMPILED_NON_MATH:
        if pattern.search(t):
            return label
    return None


def check(text: str) -> ScopeResult:
    """Run BEFORE conversation_resolver/intent classification, same slot as
    safety.check_input. in_scope=False and allow_gloss=False means: stop
    here, return fallback_text, no resolver/retrieval/verifier/generation
    call for this turn at all.

    Non-maths subjects are checked FIRST and always refuse outright (no
    gloss, no bare-definition exception) -- that's the system prompt's own
    existing policy for them, just enforced deterministically instead of
    hoping the prose rule holds. A beyond-primary MATH topic gets the
    softer bare-definition-gloss treatment below."""
    non_math = _find_non_math_subject(text)
    if non_math is not None:
        return ScopeResult(in_scope=False, topic=non_math, allow_gloss=False,
                           fallback_text=REFUSAL_TEXT)

    found = _find_topic(text)
    if found is None:
        return ScopeResult(in_scope=True)
    topic, term = found

    t = (text or "").strip()
    if _SOLVE_SIGNAL_RE.search(t):
        return ScopeResult(in_scope=False, topic=topic, allow_gloss=False,
                           fallback_text=REFUSAL_TEXT, matched_term=term)
    if _is_bare_definition(t):
        return ScopeResult(in_scope=False, topic=topic, allow_gloss=True, matched_term=term)
    # Names a beyond-primary topic without being a clean bare-definition ask
    # (extra content mixed in) -- conservative default is REFUSE, not GLOSS.
    return ScopeResult(in_scope=False, topic=topic, allow_gloss=False,
                       fallback_text=REFUSAL_TEXT, matched_term=term)


_GLOSS_SYSTEM = (
    "A Class 1-5 child (NCERT, India) asked what a maths topic is that is "
    "taught LATER, beyond primary school. Reply in 1-2 short, warm "
    "sentences with an honest, very simple idea of what it roughly means -- "
    "NO formulas, NO numbered steps, NO worked example, NO equations, and "
    "do NOT invite them to try a problem on it. End with one short "
    "sentence saying they will learn exactly how to do it later. Nothing "
    "else."
)
_GLOSS_FEWSHOT = [
    ("algebra", "Algebra is a way of doing maths where letters stand in for "
                "numbers we don't know yet. You'll learn exactly how to use "
                "it a little later on!"),
    ("integration", "Integration is a way mathematicians add up lots and "
                    "lots of tiny pieces to find a total, like area under a "
                    "curve. You'll learn exactly how it works in a later class!"),
    ("probability", "Probability is about how likely something is to "
                    "happen, like whether it will rain tomorrow. You'll "
                    "learn exactly how to work that out later on!"),
]


def generate_gloss(topic: str, chat_fn=None) -> str:
    """A small, single-purpose LLM call for the ONE case that still needs
    real generation (a bare "what is X" for a beyond-primary topic) --
    narrower and far more reliable than hoping the main TUTOR_SYSTEM
    prompt's prose rule holds inside a much longer, multi-purpose prompt
    (confirmed live it doesn't, reliably). chat_fn is injectable for tests."""
    from . import llm_client  # lazy: keeps this module import-safe offline

    messages = [{"role": "system", "content": _GLOSS_SYSTEM}]
    for q, a in _GLOSS_FEWSHOT:
        messages.append({"role": "user", "content": f"what is {q}"})
        messages.append({"role": "assistant", "content": a})
    messages.append({"role": "user", "content": f"what is {topic}"})

    # max_tokens=400, not a tight budget: confirmed live this reasoning
    # model can burn 150+ tokens on hidden thinking before emitting any
    # visible text at all (finish_reason="length", text=""), the same
    # failure mode already hardened against in verifier.py's extractor and
    # hints.py (see their own comments). A short gloss still only costs a
    # few hundred tokens even with headroom to spare.
    def call(max_tokens: int) -> str:
        fn = chat_fn or (lambda msgs: llm_client.chat(
            msgs, params={"temperature": 0.3, "max_tokens": max_tokens}))
        result = fn(messages)
        return (result.get("text") or "").strip() if isinstance(result, dict) else (result or "").strip()

    # A gloss cut off mid-word ("A logarith", seen in the v1 evaluation) is
    # worse than the fixed fallback: retry once with more room for the
    # model's hidden reasoning, then fall back.
    text = call(400)
    if not text or _looks_cut_off(text):
        text = call(800)
    if not text or _looks_cut_off(text):
        text = (f"{topic.capitalize()} is something you'll learn more about "
                "in a later class!")
    return text


_COMPLETE_ENDING_RE = re.compile(r"[.!?)\"'’”]\s*$|[\U0001F300-\U0001FAFF☀-➿️]\s*$")


def _looks_cut_off(text: str) -> bool:
    return not _COMPLETE_ENDING_RE.search(text)


# ------------------------------------------------------------ small-model check
# The word rules above only see phrasings someone listed. On 40 fresh
# disguised questions written by a person who never saw them they stopped 4,
# so a second, concept-level check by a SMALL model (its own Groq rate
# limits) runs after them -- but only where a new problem starts (a
# session opener, a new question, a changed problem), never on attempts,
# hints, confusion or give-ups, which cannot bring in a new topic. Bare
# arithmetic skips it, and any failure means "in scope" (the word rules'
# verdict stands). The prompt is written from the Class 1-5 topic list
# (docs/verified_ncert_class_1_5_topics.md) and the beyond-primary topics
# above, never from test questions.
SCOPE_MODEL = "openai/gpt-oss-20b"
SCOPE_PARAMS = {"temperature": 0.0, "max_tokens": 600, "top_p": 1.0, "reasoning_effort": "medium"}

